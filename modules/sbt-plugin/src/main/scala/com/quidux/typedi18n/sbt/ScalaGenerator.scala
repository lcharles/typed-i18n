package com.quidux.typedi18n.sbt

private[sbt] object ScalaGenerator {
  private final case class Node(
      path: Vector[String],
      children: Vector[Node],
      messages: Vector[MessageDefinition]
  )

  def generate(schema: MessageSchema, catalogs: Vector[LocaleCatalog] = Vector.empty): String = {
    val root = buildNode(Vector.empty, schema.messages)
    val packageQualifier = schema.packageName.split("\\.").last
    val builder = new StringBuilder
    builder.append(s"package ${schema.packageName}\n\n")
    builder.append("// Generated by sbt-typed-i18n. Do not edit.\n")
    if (catalogs.exists(_.fluent.nonEmpty)) {
      val license = scala.io.Source.fromInputStream(getClass.getResourceAsStream("/typed-i18n/UNICODE-LICENSE"), "UTF-8")
      try builder.append(license.getLines().map("// " + _).mkString("", "\n", "\n")) finally license.close()
    }
    builder.append("import typed.i18n.*\n\n")
    builder.append("final class Strings private (private val renderer: MessageRenderer):\n")
    root.children.foreach { child =>
      builder.append(s"  val ${child.path.last}: ${IdentifierValidation.className(child.path)} =\n")
      builder.append(s"    new ${IdentifierValidation.className(child.path)}(renderer)\n\n")
    }
    builder.append("object Strings:\n")
    if (catalogs.nonEmpty) appendBundled(builder, catalogs)
    builder.append("  lazy val schema: MessageSchema =\n")
    builder.append(s"    MessageSchema(${literal(schema.packageName)}, Vector(\n")
    schema.messages.sortBy(_.id).zipWithIndex.foreach { case (message, index) =>
      builder.append(s"      MessageDefinition(${literal(message.id)}, Vector(")
      builder.append(message.arguments.sortBy(_._1).map { case (name, argumentType) =>
        s"${literal(name)} -> ArgumentType.${runtimeTypeName(argumentType)}"
      }.mkString(", "))
      builder.append("))")
      if (index < schema.messages.size - 1) builder.append(",")
      builder.append("\n")
    }
    builder.append("    ))\n\n")
    builder.append("  def fromCatalog(catalog: ValidatedCatalog): Either[CatalogCompatibilityError, Strings] =\n")
    builder.append("    if catalog.schema == schema then Right(new Strings(catalog.renderer))\n")
    builder.append("    else Left(CatalogCompatibilityError(schema.packageName, catalog.schema.packageName))\n\n")
    builder.append("  def unsafeFromCatalog(catalog: ValidatedCatalog): Strings =\n")
    builder.append("    fromCatalog(catalog).fold(error => throw IllegalArgumentException(error.toString), identity)\n")
    allNodes(root).foreach { node =>
      builder.append("\n")
      builder.append(s"final class ${IdentifierValidation.className(node.path)} private[$packageQualifier] (\n")
      builder.append("    private val renderer: MessageRenderer\n")
      builder.append("):\n")
      node.children.foreach { child =>
        builder.append(s"  val ${child.path.last}: ${IdentifierValidation.className(child.path)} =\n")
        builder.append(s"    new ${IdentifierValidation.className(child.path)}(renderer)\n\n")
      }
      node.messages.sortBy(_.id).foreach { message =>
        val methodName = message.id.split("\\.").last
        val sortedArguments = message.arguments.sortBy(_._1)
        val parameters = sortedArguments.map { case (name, argumentType) =>
          s"$name: ${argumentType.scalaType}"
        }.mkString(", ")
        if (parameters.isEmpty)
          builder.append(s"  def $methodName: String =\n")
        else
          builder.append(s"  def $methodName($parameters): String =\n")
        if (parameters.isEmpty) {
          builder.append(s"    this.renderer.render(${literal(message.id)})\n\n")
        } else {
          builder.append("    this.renderer.render(\n")
          builder.append(s"      ${literal(message.id)},\n")
          builder.append("      Map(\n")
          sortedArguments.zipWithIndex.foreach { case ((name, argumentType), index) =>
            builder.append(
              s"        ${literal(name)} -> MessageArgument.${argumentType.constructor}($name)"
            )
            if (index < sortedArguments.size - 1) builder.append(",")
            builder.append("\n")
          }
          builder.append("      )\n")
          builder.append("    )\n\n")
        }
      }
    }
    builder.result()
  }

  private def appendBundled(builder: StringBuilder, catalogs: Vector[LocaleCatalog]): Unit = {
    val sorted = catalogs.sortBy(_.locale)
    builder.append("  enum Locale(val tag: String):\n")
    sorted.foreach { catalog =>
      builder.append(s"    case ${CatalogCompiler.localeCase(catalog.locale)} extends Locale(${literal(catalog.locale)})\n")
    }
    builder.append("\n  val availableLocales: Vector[Locale] = Locale.values.toVector\n\n")
    builder.append("  def localeFor(preferred: Seq[String], fallback: Locale): Locale =\n")
    builder.append("    LocaleMatching.lookup(preferred, availableLocales.map(_.tag))\n")
    builder.append("      .flatMap(tag => availableLocales.find(_.tag == tag))\n")
    builder.append("      .getOrElse(fallback)\n\n")
    builder.append("  def forLocale(locale: Locale): Strings =\n")
    builder.append("    locale match\n")
    sorted.foreach { catalog =>
      val name = CatalogCompiler.localeCase(catalog.locale)
      builder.append(s"      case Locale.$name => Bundled$name.strings\n")
    }
    builder.append("\n")
    sorted.foreach { catalog =>
      builder.append(s"  private object Bundled${CatalogCompiler.localeCase(catalog.locale)} extends MessageRenderer:\n")
      builder.append("    val strings: Strings = new Strings(this)\n\n")
      if (catalog.fluent.nonEmpty) builder.append(PluralCompiler.generate(catalog.locale))
      builder.append("    override def render(messageId: String, arguments: Map[String, MessageArgument]): String =\n")
      builder.append("      messageId match\n")
      catalog.messages.toVector.sortBy(_._1).foreach { case (id, template) =>
        val parts = CatalogCompiler.parse(template).fold(problem => sys.error(problem), identity)
        val expression = parts.map {
          case TemplatePart.Text(text) => literal(text)
          case TemplatePart.Argument(name) => s"arguments(${literal(name)}).rendered"
        }.mkString(" + ")
        builder.append(s"        case ${literal(id)} =>\n          $expression\n")
      }
      catalog.fluent.foreach(_.toVector.sortBy(_._1).foreach { case (id, pattern) =>
        builder.append(s"        case ${literal(id)} =>\n          ${FluentGenerator.pattern(pattern)}\n")
      })
      builder.append("        case _ => throw IllegalArgumentException(s\"Unknown message '$messageId'\")\n\n")
    }
  }

  private def buildNode(
      path: Vector[String],
      messages: Vector[MessageDefinition]
  ): Node = {
    val depth = path.length
    val direct = messages.filter(_.id.split("\\.").length == depth + 1)
    val descendants = messages.filter(_.id.split("\\.").length > depth + 1)
    val children = descendants
      .groupBy(_.id.split("\\.")(depth))
      .toVector
      .sortBy(_._1)
      .map { case (segment, childMessages) => buildNode(path :+ segment, childMessages) }
    Node(path, children, direct)
  }

  private def allNodes(root: Node): Vector[Node] =
    root.children.flatMap(child => child +: allNodes(child))

  private def runtimeTypeName(argumentType: ArgumentType): String = argumentType match {
    case ArgumentType.StringType  => "StringType"
    case ArgumentType.IntType     => "IntType"
    case ArgumentType.LongType    => "LongType"
    case ArgumentType.DecimalType => "DecimalType"
    case ArgumentType.BooleanType => "BooleanType"
  }

  private[sbt] def literal(value: String): String = {
    val escaped = value.flatMap {
      case '\\' => "\\\\"
      case '"'  => "\\\""
      case '\n' => "\\n"
      case '\r' => "\\r"
      case '\t' => "\\t"
      case char if char < ' ' => f"\\u${char.toInt}%04x"
      case char => char.toString
    }
    '"' + escaped + '"'
  }
}
